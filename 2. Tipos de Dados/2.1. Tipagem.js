// Tipagem é a forma como os dados são classificados em uma linguagem de programação.

console.log("Tipos de dados");
console.log("1 =", typeof 1);
console.log("1.2 =", typeof 1.2);
console.log("Natan =", typeof "Natan");
console.log("'151' =", typeof "151");
console.log("true =", typeof true);
console.log("'true' =", typeof "true");

console.log(2 + 2);
console.log("2" + 2);
console.log(typeof ("2" + 2));